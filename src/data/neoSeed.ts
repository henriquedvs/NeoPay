export function buildCardTimeline(currentStatus: CardLifecycleStatus): CardOrderTimelineItem[] {
  const idx = CARD_TIMELINE_STEPS.findIndex((s) => s.status === currentStatus);
  return CARD_TIMELINE_STEPS.map((step, i) => ({
    status: step.status,
    label: step.label,
    dateLabel: i <= idx ? 'Concluído' : 'Previsto',
    done: i <= idx,
  }));
}

